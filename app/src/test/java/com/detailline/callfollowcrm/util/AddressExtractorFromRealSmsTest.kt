package com.detailline.callfollowcrm.util

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

/**
 * 🧾 **사장님 실제 받은 문자**에서 뽑은 성적표. (2026-09-16, 갤S9+ 수신함 1,084건 실측)
 *
 * 왜 이게 중요한가: 그 전까지는 제가 **지어낸 예문**으로만 맞춰보고 "95%" 라고 말했다.
 *   진짜 문자로 돌려보니 **주소는 잡는데 단지명·동호수가 잘려나가고** 있었다 —
 *   "서울 영등포구 국제금융로 39 브라이튼여의도 103동 1210호" → "…국제금융로 39" 에서 끝.
 *   사장님 고객은 대부분 단지명을 같이 적기 때문에, 25건 중 6건이 이 모양이었다.
 *   (동호수가 없으면 현장에 가서 어느 집인지 모른다 = 반쪽짜리 주소)
 *
 * ⚠️ 여기 문장들은 **실제 고객 문자에서 가져온 것**이다. 규칙을 고칠 때 이 점수가 떨어지면
 *    사장님이 바로 불편해진다. 지우지 말고, 새 실패를 발견하면 한 줄 추가할 것.
 */
class AddressExtractorFromRealSmsTest {

    private fun ex(body: String) = AddressExtractor.extractOne(body)

    // ── 단지명이 중간에 낀 형태 (가장 흔했고, 가장 많이 잘리던 것) ──

    @Test
    fun `도로명 + 단지명 + 동호수를 통째로 잡는다`() {
        assertEquals(
            "서울 영등포구 국제금융로 39 브라이튼여의도 103동 1210호",
            ex("시공접수서 주소입력이 안되네요. 서울 영등포구 국제금융로 39 브라이튼여의도 103동 1210호 입니다.")
        )
        assertEquals(
            "경기도 수원시 망포로 14 하늘채아파트 224동 1201호",
            ex("경기도 수원시 망포로 14 하늘채아파트 224동 1201호")
        )
        assertEquals(
            "화성시 병점노을로31 병점역아이파크캐슬 103동 501호",
            ex("송금했습니다. 화성시 병점노을로31 병점역아이파크캐슬 103동 501호 입니다.")
        )
        assertEquals(
            "경기도 시흥시 은행로 108 벽산3차 304동 1105호",
            ex("경기도 시흥시 은행로 108 벽산3차 304동 1105호 입니다")
        )
    }

    @Test
    fun `번길 뒤 숫자까지 번지로 본다`() {
        // 2026-09-18: '경기도' 가 앞에 붙게 됐다. 가지 도로명(ROAD_BRANCH) 패턴이 광역시도까지
        //   같이 잡아주기 때문 — 주소가 **더 완전해진 것**이라 기대값을 올렸다. 나머지는 그대로.
        assertEquals(
            "경기도 용인시 수지구 풍덕천로 171번길9 수지파크푸르지오 103동2001호",
            ex("네. 경기도 용인시 수지구 풍덕천로 171번길9 수지파크푸르지오 103동2001호")
        )
    }

    @Test
    fun `가지 도로명은 통째로 - 동탄산척로2다길이 동탄산척로2로 잘리지 않는다`() {
        // 2026-09-17 사장님 실제 문자. 한국 도로명은 큰 길에서 갈라진 길에 <숫자><한글>길 을 붙인다.
        //   그 숫자는 **길 이름의 일부**인데, 건물번호로 오해해 떼어가면 '다길' 이 버려져
        //   "화성시 동탄구 동탄산척로2" 라는 있지도 않은 주소가 됐었다.
        assertEquals(
            "화성시 동탄구 동탄산척로2다길",
            ex("배송(도착)주소 : 화성시 동탄구\n동탄산척로2다길")
        )
    }

    @Test
    fun `번길이 아닌 뒤 숫자는 주워오지 않는다`() {
        // "84 1층" 의 1, "1656 8 유성사우나" 의 8 을 번지로 오해하면 안 된다
        assertEquals("서울 용산구 우사단로10길 84",
            ex("[중대본] 서울 용산구 우사단로10길 84 1층, 와인바 방문자는 보건소에서 검사받으세요"))
    }

    @Test
    fun `시와 구가 같이 오면 둘 다 잡는다`() {
        assertEquals(
            "화성시 만세구 새솔동6 송산그린시티5차노블랜드리버파크 503동 302호",
            ex("화성시 만세구 새솔동6 송산그린시티5차노블랜드리버파크 503동 302호 입니다")
        )
    }

    // ── 브랜드 앞말 ──

    @Test
    fun `공백으로 떨어진 단지명도 끌어온다`() {
        assertEquals("동탄역 포레너스 아파트 475동 901호",
            ex("김홍열 2026.09.19.09시 동탄역 포레너스 아파트 475동 901호 입니다."))
    }

    @Test
    fun `말이 주소에 딸려 들어오지 않는다`() {
        // '보넸고요' 같은 어미로 끝나는 말은 주소가 아니다
        assertEquals("현대아파트 102동2504호",
            ex("보넸고요 현대아파트 102동2504호 7월20일 에 보겠습니다 이정주 앞으로 보넸어요"))
    }

    // ── 붙여 쓴 주소 ──

    @Test
    fun `띄어쓰기 없이 보내도 잡는다`() {
        assertEquals("경기도시흥시거모동 1656", ex("경기도시흥시거모동 1656 8 유성사우나3층"))
        assertEquals("대원아파트101동104호", ex("대원아파트101동104호"))
        assertEquals("동탄역대방디엠시티 101동 3702호", ex("동탄역대방디엠시티 101동 3702호 입니다."))
    }

    // ── 주소가 아닌 진짜 문자 (1,084건 중 광고·인증 문자에서 오탐 0이었다) ──

    @Test
    fun `주소 아닌 문자는 안 잡는다`() {
        listOf(
            "네 확인요",
            "네 감사합니다",
            "고객 컨펌 잘 받고 끝내야하는데 컨펌 좀 잘 받아주세요",
            "입금 했습니다 확인 부탁드려요",
            "내일 오전에 가능하실까요?",
        ).forEach { assertNull("주소가 아닌데 잡음: $it → ${ex(it)}", ex(it)) }
    }
}
