    /** 이름 → 그 이름을 쓰는 자리들. "중구" 처럼 여러 시·도에 있으면 여러 개. */
    private val byName: Map<String, List<Spot>> by lazy {
        val out = HashMap<String, MutableList<Spot>>()
        for (line in RAW.lineSequence()) {
            val parts = line.split('|')
            if (parts.size < 2) continue
            val sido = parts[0]
            for (i in 1 until parts.size) {
                val cell = parts[i].split(':', limit = 2)
                if (cell.size < 2) continue
                val nm = cell[0].trim()
                val ll = cell[1].split(',', limit = 2)
                if (ll.size < 2) continue
                val la = ll[0].trim().toDoubleOrNull() ?: continue
                val lo = ll[1].trim().toDoubleOrNull() ?: continue
                out.getOrPut(nm) { mutableListOf() }.add(Spot(nm, sido, la, lo))
            }
        }
        out
    }

