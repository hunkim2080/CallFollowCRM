    fun forTrade(trade: String?): List<StarterItem> {
        val t = trade?.trim().orEmpty()
        if (t.isEmpty()) return emptyList()
        byTrade[t]?.let { return it }
        return byTrade.entries.firstOrNull { (k, _) -> t.contains(k) || k.contains(t) }?.value ?: emptyList()
    }
